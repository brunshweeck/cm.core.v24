    gint CharacterData02::properties(gint ch) {
        gchar offset = (gchar) ch;
        int props = A[Y[X[offset >> 5] | ((offset >> 1) & 0xF)] | (offset & 0x1)];
        return props;
    }

    gint CharacterData02::propertiesEx(gint ch) {
        gchar offset = (gchar) ch;
        int props = B[Y[X[offset >> 5] | ((offset >> 1) & 0xF)] | (offset & 0x1)];
        return props;
    }

